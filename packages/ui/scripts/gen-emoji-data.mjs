// Generates `src/lib/emoji/emoji-data.ts` from the pure-data package
// `unicode-emoji-json` (no UI widget). Run: `node scripts/gen-emoji-data.mjs`.
//
// We OWN the emitted dataset (committed); the dev-only source package is just
// the Unicode CLDR data. Smileys & Emotion + People & Body are merged into one
// "Smileys & People" category to match the LobeHub picker layout.
import { createRequire } from 'node:module';
import { writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const groups = require('unicode-emoji-json/data-by-group.json');

const MERGE = {
  'Smileys & Emotion': 'Smileys & People',
  'People & Body': 'Smileys & People',
};
const ID = {
  'Smileys & People': 'smileys_people',
  'Animals & Nature': 'animals_nature',
  'Food & Drink': 'food_drink',
  'Travel & Places': 'travel_places',
  Activities: 'activities',
  Objects: 'objects',
  Symbols: 'symbols',
  Flags: 'flags',
};
const ORDER = [
  'Smileys & People',
  'Animals & Nature',
  'Food & Drink',
  'Travel & Places',
  'Activities',
  'Objects',
  'Symbols',
  'Flags',
];

const byName = new Map();
for (const g of groups) {
  const name = MERGE[g.name] ?? g.name;
  if (!byName.has(name)) byName.set(name, []);
  const arr = byName.get(name);
  for (const em of g.emojis) {
    const tokens = new Set(
      `${em.name} ${em.slug.replace(/_/g, ' ')}`
        .toLowerCase()
        .split(/\s+/)
        .filter(Boolean),
    );
    arr.push({ e: em.emoji, n: em.name, k: [...tokens].join(' ') });
  }
}

const cats = ORDER.map((name) => ({
  id: ID[name],
  name,
  emojis: byName.get(name) ?? [],
}));

const header =
  '// AUTO-GENERATED by scripts/gen-emoji-data.mjs from `unicode-emoji-json`.\n' +
  '// Do not edit by hand — run `node scripts/gen-emoji-data.mjs` to regenerate.\n\n';
const types =
  'export interface EmojiDatum {\n' +
  '  /** The emoji glyph. */\n  e: string;\n' +
  '  /** Human-readable name. */\n  n: string;\n' +
  '  /** Lowercased search text (name + slug tokens). */\n  k: string;\n}\n\n' +
  'export interface EmojiCategory {\n' +
  '  id: string;\n  name: string;\n  emojis: EmojiDatum[];\n}\n\n';
const body = `export const EMOJI_CATEGORIES: EmojiCategory[] = ${JSON.stringify(
  cats,
)};\n`;

const outDir = resolve(dirname(fileURLToPath(import.meta.url)), '../src/lib/emoji');
mkdirSync(outDir, { recursive: true });
writeFileSync(resolve(outDir, 'emoji-data.ts'), header + types + body);

const total = cats.reduce((n, c) => n + c.emojis.length, 0);
console.log(`wrote ${total} emoji in ${cats.length} categories`);
