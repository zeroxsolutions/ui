import type { ReactNode } from 'react';
import Animated, { useAnimatedProps } from 'react-native-reanimated';
import Svg, { Path, Rect } from 'react-native-svg';
import { transformProps, useIconMotion, type AnimatedIconProps, type IconHandle } from '../../lib/icon-motion';

/** The handle a control starts and stops {@link BlocksIcon} through. */
type BlocksIconHandle = IconHandle;

const AnimatedRect = Animated.createAnimatedComponent(Rect);

/**
 * Lucide's blocks icon, whose loose block slides down and left into the gap and back when started. Hidden from a
 * screen reader: the control around it says what it does.
 */
function BlocksIcon({
  ref,
  color = 'currentColor',
  size = 24,
  strokeWidth = 2,
  absoluteStrokeWidth: _absoluteStrokeWidth,
  nonScalingStroke: _nonScalingStroke,
  ...props
}: AnimatedIconProps): ReactNode {
  const progress = useIconMotion(ref);
  const block = useAnimatedProps(() => transformProps({ x: -4 * progress.value, y: 4 * progress.value }));

  return (
    <Svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke={color}
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      {...props}
      accessibilityElementsHidden
      importantForAccessibility="no-hide-descendants"
    >
      <Path d="M10 22V7a1 1 0 0 0-1-1H4a2 2 0 0 0-2 2v12a2 2 0 0 0 2 2h12a2 2 0 0 0 2-2v-5a1 1 0 0 0-1-1H2" />
      <AnimatedRect x="14" y="2" width="8" height="8" rx="1" animatedProps={block} />
    </Svg>
  );
}

export { BlocksIcon };
export type { BlocksIconHandle };
